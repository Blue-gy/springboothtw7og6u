<script>
  export default {
    data() {
	  let self = this
      return {
        id: '',
        baseUrl: '',
        ro:{
				shebeimingcheng : false,
				kucunshuliang : false,
				shebeitupian : false,
				shebeijianjie : false,
				zulinjiage : false,
				zulinjine : false,
				zulinshijian : false,
				yonghuzhanghao : false,
				xingming : false,
				guihaishijian : false,
				crossuserid : false,
				crossrefid : false,
				sfsh : false,
				shhf : false,
        },
        type: '',
        userTableName: localStorage.getItem('UserTableName'),
        ruleForm: {
          shebeimingcheng: '',
          kucunshuliang: '',
          shebeitupian: '',
          shebeijianjie: '',
          zulinjiage: '',
          zulinjine: '',
          zulinshijian: '',
          yonghuzhanghao: '',
          xingming: '',
          guihaishijian: '',
          crossuserid: '',
          crossrefid: '',
        },


        rules: {
          shebeimingcheng: [
          ],
          kucunshuliang: [
            { validator: this.$validate.isIntNumer, trigger: 'blur' },
          ],
          shebeitupian: [
          ],
          shebeijianjie: [
          ],
          zulinjiage: [
            { validator: this.$validate.isIntNumer, trigger: 'blur' },
          ],
          zulinjine: [
            { validator: this.$validate.isIntNumer, trigger: 'blur' },
          ],
          zulinshijian: [
          ],
          yonghuzhanghao: [
          ],
          xingming: [
          ],
          guihaishijian: [
          ],
          crossuserid: [
          ],
          crossrefid: [
          ],
          sfsh: [
          ],
          shhf: [
          ],
        },
		centerType: false,
      };
    },
    computed: {



    },
    components: {
    },
    created() {
		if(this.$route.query.centerType){
			this.centerType = true
		}
	  //this.bg();
      let type = this.$route.query.type ? this.$route.query.type : '';
      this.init(type);
      this.baseUrl = this.$config.baseUrl;
      this.ruleForm.guihaishijian = this.getCurDateTime()
    },
    methods: {
      getMakeZero(s) {
          return s < 10 ? '0' + s : s;
      },
      // 下载
      download(file){
        window.open(`${file}`)
      },
      // 初始化
      init(type) {
        this.type = type;
        if(type=='cross'){
          var obj = JSON.parse(localStorage.getItem('crossObj'));
          for (var o in obj){
            if(o=='shebeimingcheng'){
              this.ruleForm.shebeimingcheng = obj[o];
              this.ro.shebeimingcheng = true;
              continue;
            }
            if(o=='kucunshuliang'){
              this.ruleForm.kucunshuliang = obj[o];
              this.ro.kucunshuliang = true;
              continue;
            }
            if(o=='shebeitupian'){
              this.ruleForm.shebeitupian = obj[o].split(",")[0];
              this.ro.shebeitupian = true;
              continue;
            }
            if(o=='shebeijianjie'){
              this.ruleForm.shebeijianjie = obj[o];
              this.ro.shebeijianjie = true;
              continue;
            }
            if(o=='zulinjiage'){
              this.ruleForm.zulinjiage = obj[o];
              this.ro.zulinjiage = true;
              continue;
            }
            if(o=='zulinjine'){
              this.ruleForm.zulinjine = obj[o];
              this.ro.zulinjine = true;
              continue;
            }
            if(o=='zulinshijian'){
              this.ruleForm.zulinshijian = obj[o];
              this.ro.zulinshijian = true;
              continue;
            }
            if(o=='yonghuzhanghao'){
              this.ruleForm.yonghuzhanghao = obj[o];
              this.ro.yonghuzhanghao = true;
              continue;
            }
            if(o=='xingming'){
              this.ruleForm.xingming = obj[o];
              this.ro.xingming = true;
              continue;
            }
            if(o=='guihaishijian'){
              this.ruleForm.guihaishijian = obj[o];
              this.ro.guihaishijian = true;
              continue;
            }
            if(o=='crossuserid'){
              this.ruleForm.crossuserid = obj[o];
              this.ro.crossuserid = true;
              continue;
            }
            if(o=='crossrefid'){
              this.ruleForm.crossrefid = obj[o];
              this.ro.crossrefid = true;
              continue;
            }
          }
        }else if(type=='edit'){
			this.info()
		}
        // 获取用户信息
        this.$http.get(this.userTableName + '/session', {emulateJSON: true}).then(res => {
          if (res.data.code == 0) {
            var json = res.data.data;
            if((json.yonghuzhanghao!=''&&json.yonghuzhanghao) || json.yonghuzhanghao==0){
                this.ruleForm.yonghuzhanghao = json.yonghuzhanghao
            }
            if((json.xingming!=''&&json.xingming) || json.xingming==0){
                this.ruleForm.xingming = json.xingming
            }
          }
        });

		if (localStorage.getItem('raffleType') && localStorage.getItem('raffleType') != null) {
			localStorage.removeItem('raffleType')
			setTimeout(() => {
				this.onSubmit()
			}, 300)
		}
      },

    // 多级联动参数
      // 多级联动参数
      info() {
        this.$http.get(`zulinguihai/detail/${this.$route.query.id}`, {emulateJSON: true}).then(res => {
          if (res.data.code == 0) {
            this.ruleForm = res.data.data;
          }
        });
      },
      // 提交
      onSubmit() {

			//更新跨表属性
			var crossuserid;
			var crossrefid;
			var crossoptnum;
			this.$refs["ruleForm"].validate(valid => {
				if(valid) {
					if(this.type=='cross'){
						var statusColumnName = localStorage.getItem('statusColumnName');
						var statusColumnValue = localStorage.getItem('statusColumnValue');
						if(statusColumnName && statusColumnName!='') {
							var obj = JSON.parse(localStorage.getItem('crossObj'));
							if(!statusColumnName.startsWith("[")) {
								for (var o in obj){
									if(o==statusColumnName){
										obj[o] = statusColumnValue;
									}
								}
								var table = localStorage.getItem('crossTable');
								this.$http.post(table+'/update', obj).then(res => {});
							} else {
								crossuserid=Number(localStorage.getItem('frontUserid'));
								crossrefid=obj['id'];
								crossoptnum=localStorage.getItem('statusColumnName');
								crossoptnum=crossoptnum.replace(/\[/,"").replace(/\]/,"");
							}
						}
					}
					if(crossrefid && crossuserid) {
						this.ruleForm.crossuserid=crossuserid;
						this.ruleForm.crossrefid=crossrefid;
						var params = {
							page: 1,
							limit: 10,
							crossuserid:crossuserid,
							crossrefid:crossrefid,
						}
						this.$http.get('zulinguihai/list', {
							params: params
						}).then(res => {
							if(res.data.data.total>=crossoptnum) {
								this.$message({
									message: localStorage.getItem('tips'),
									type: 'error',
									duration: 1500,
								});
								return false;
							} else {
								// 跨表计算


								this.$http.post(`zulinguihai/${this.ruleForm.id?'update':this.centerType?'save':'add'}`, this.ruleForm).then(res => {
									if (res.data.code == 0) {
										this.$message({
											message: '操作成功',
											type: 'success',
											duration: 1500,
											onClose: () => {
												this.$router.go(-1);
											}
										});
									} else {
										this.$message({
											message: res.data.msg,
											type: 'error',
											duration: 1500
										});
									}
								});
							}
						});
					} else {


						this.$http.post(`zulinguihai/${this.ruleForm.id?'update':this.centerType?'save':'add'}`, this.ruleForm).then(res => {
							if (res.data.code == 0) {
								this.$message({
									message: '操作成功',
									type: 'success',
									duration: 1500,
									onClose: () => {
										this.$router.go(-1);
									}
								});
							} else {
								this.$message({
									message: res.data.msg,
									type: 'error',
									duration: 1500
								});
							}
						});
					}
				}
			});
		},
		// 获取uuid
		getUUID () {
			return new Date().getTime();
		},
		// 返回
		back() {
			this.$router.go(-1);
		},
      shebeitupianUploadChange(fileUrls) {
          this.ruleForm.shebeitupian = fileUrls.replace(new RegExp(this.$config.baseUrl,"g"),"");;
      },
    }
  };
</script>

